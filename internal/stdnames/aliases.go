// Package stdnames holds the one table that says which user-facing qualified
// name (`List.map`) is which internal flat builtin (`listMap`).
//
// The type checker and the Go runtime each kept a copy, 390 entries long and
// identical entry for entry, with a drift test to notice when one fell behind.
// Both read this one now, so "added to typecheck, forgotten in the runtime"
// cannot be written. It is a leaf package on purpose: the runtime must not
// import the checker.
